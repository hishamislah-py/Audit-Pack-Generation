"""Deterministic outcome summary (final-pack schema 1.3; renderer 3.0 page 1). Built by fixed rules from values already in
the final pack (the engine's control outcomes, control register, evidence register, missing-evidence register, exception
register and the analyst's recorded decisions). It never calls a model, never recalculates an amount and never states a
cause, a resolution, an audit opinion or compliance. Every number is either copied from an engine field or a count of
stored rows; the `derived` list names the counts so the report can label them.

validate.py recomputes it from the same pack and refuses a pack whose stored outcome_summary differs.
"""
from .model import OUTCOME_SUMMARY_VERSION

GENERATED_BY = ("Deterministic rules applied to the stored engine results (uc042-outcome-summary/1.0). "
                "Not generated by AI.")
MEANING = ("This is the deterministic reconciliation engine's result for the supplied synthetic data. It is not an "
           "independent audit conclusion, not an audit opinion and not a compliance certification.")


def _n(x):
    return f"{x:,}"


def _plural(n, one, many):
    return one if n == 1 else many


def outcome_figures(final):
    s = final["executive_summary"]["deterministic"]
    co = s["control_outcomes"]
    by = dict(co["by_outcome"])
    checks = final["reconciliation_results"]["control_checks"]
    files = final["source_inventory"]["files"]
    missing = final["source_inventory"]["missing_evidence"]["items"]
    reg = final["exception_register"]
    required = [f for f in files if f["requirement"] == "REQUIRED"]
    optional = [f for f in files if f["requirement"] != "REQUIRED"]
    decisions = [e["investigation"].get("analyst_review") for e in reg if e["investigation"].get("analyst_review")]
    return {
        "engine_case_status": s["engine_case_status"], "evidence_completeness": s["evidence_completeness"],
        "control_outcome_summary": co["summary"],
        "control_results_total": co["total_results"], "control_results_by_outcome": by,
        "control_results_passed": by.get("PASS", 0), "control_results_failed": by.get("FAIL", 0),
        "control_results_not_applicable": by.get("NOT_APPLICABLE", 0),
        "control_results_insufficient_evidence": by.get("INSUFFICIENT_EVIDENCE", 0),
        "checks_total": co["check_types"], "checks_with_results": co["check_types_with_results"],
        "checks_listed": len(checks),
        "checks_with_failures": list(co.get("checks_with_failures", [])),
        "checks_not_fully_assessed": list(co.get("checks_not_fully_assessed", [])),
        "checks_no_findings": list(co.get("checks_no_findings", [])),
        "exceptions_total": len(reg), "exceptions_unresolved": sum(e["resolution_status"] == "UNRESOLVED" for e in reg),
        "exceptions_by_severity": dict(final["executive_summary"]["exceptions"]["by_severity"]),
        "source_files_total": len(files), "required_files_total": len(required),
        "required_files_present": sum(f["availability"] == "PRESENT" for f in required),
        "optional_files_total": len(optional), "optional_files_present": sum(f["availability"] == "PRESENT" for f in optional),
        "missing_evidence_items": len(missing), "engine_missing_evidence_items": s["missing_evidence_items"],
        "ai_investigations_included": len(final["ai_investigations"]),
        "analyst_decisions_accept": sum(d["decision"] == "ACCEPT" for d in decisions),
        "analyst_decisions_reject": sum(d["decision"] == "REJECT" for d in decisions),
        "exceptions_not_investigated": sum(e["investigation"]["inclusion"] == "NOT_INVESTIGATED" for e in reg),
        "exceptions_excluded_by_analyst": sum(e["investigation"]["inclusion"] == "EXCLUDED_BY_ANALYST" for e in reg),
        "reconciliation_days": final["metadata"]["reconciliation_days_count"],
        "accounts": len(final["metadata"]["accounts"]), "currencies": list(final["metadata"]["currency_scope"]),
    }


DERIVED = ["checks_listed", "exceptions_total", "exceptions_unresolved", "source_files_total", "required_files_total",
           "required_files_present", "optional_files_total", "optional_files_present", "missing_evidence_items",
           "ai_investigations_included", "analyst_decisions_accept", "analyst_decisions_reject", "exceptions_not_investigated",
           "exceptions_excluded_by_analyst", "accounts"]


def _headline(f):
    total, passed, checks = f["control_results_total"], f["control_results_passed"], f["checks_total"]
    out = [f"{_n(passed)} of {_n(total)} control results passed across {_n(checks)} checks."]
    rest = []
    if f["control_results_not_applicable"]:
        rest.append(f"{_n(f['control_results_not_applicable'])} {_plural(f['control_results_not_applicable'], 'was', 'were')} "
                    "not applicable")
    if f["control_results_insufficient_evidence"]:
        rest.append(f"{_n(f['control_results_insufficient_evidence'])} could not be assessed (insufficient evidence)")
    other = {k: v for k, v in f["control_results_by_outcome"].items()
             if k not in ("PASS", "FAIL", "NOT_APPLICABLE", "INSUFFICIENT_EVIDENCE") and v}
    rest += [f"{_n(v)} {k}" for k, v in sorted(other.items())]
    if rest:
        out.append("Of the remaining results, " + "; ".join(rest) + ".")
    failed = f["control_results_failed"]
    out.append("Zero failed control results." if not failed else
               f"{_n(failed)} failed control {_plural(failed, 'result', 'results')}.")
    n = f["exceptions_total"]
    out.append("Zero exceptions raised." if not n else
               f"{_n(n)} {_plural(n, 'exception', 'exceptions')} raised; {'it remains' if n == 1 else 'all remain'} UNRESOLVED.")
    if not n:
        out.append("No AI investigation was required.")
    return " ".join(out)


def _statements(f):
    out = []
    if f["checks_no_findings"]:
        k = len(f["checks_no_findings"])
        out.append(f"{k} {_plural(k, 'check', 'checks')} ({', '.join(f['checks_no_findings'])}) ran and reported no findings; "
                   f"{_plural(k, 'it emits', 'they emit')} a result only when a problem is found, so "
                   f"{_plural(k, 'it adds', 'they add')} nothing to the passed results.")
    if f["checks_with_failures"]:
        out.append(f"Checks with failed results: {', '.join(f['checks_with_failures'])}.")
    if f["checks_not_fully_assessed"]:
        out.append(f"Checks not fully assessed (insufficient evidence): {', '.join(f['checks_not_fully_assessed'])}.")
    req, pres = f["required_files_total"], f["required_files_present"]
    if req and req == pres:
        out.append(f"All {_n(req)} required source files were present" +
                   (f" (and {_n(f['optional_files_present'])} of {_n(f['optional_files_total'])} optional files)." if f["optional_files_total"] else "."))
    else:
        out.append(f"{_n(pres)} of {_n(req)} required source files were present.")
    m = f["missing_evidence_items"]
    out.append("The engine recorded no missing evidence." if not m else
               f"The engine recorded {_n(m)} missing-evidence {_plural(m, 'item', 'items')} (evidence expected but not available); "
               "the affected results are shown as not available, never as zero.")
    n = f["exceptions_total"]
    if n:
        inc, rej = f["ai_investigations_included"], f["analyst_decisions_reject"]
        parts = [f"{_n(inc)} AI {_plural(inc, 'investigation', 'investigations')} included after the analyst accepted "
                 f"{_plural(inc, 'it', 'them')}"]
        if rej:
            parts.append(f"{_n(rej)} rejected by the analyst (AI content excluded)")
        if f["exceptions_not_investigated"]:
            parts.append(f"{_n(f['exceptions_not_investigated'])} not investigated")
        if f["exceptions_excluded_by_analyst"]:
            parts.append(f"{_n(f['exceptions_excluded_by_analyst'])} excluded from AI investigation by the analyst")
        out.append("AI investigation: " + "; ".join(parts) + ". No AI investigation or analyst decision resolves an exception.")
    out.append(MEANING)
    return out


def outcome_summary(final):
    """The deterministic outcome summary of a final pack (its content without outcome_summary itself)."""
    f = outcome_figures(final)
    return {"version": OUTCOME_SUMMARY_VERSION, "generated_by": GENERATED_BY, "figures": f, "derived_counts": list(DERIVED),
            "headline": _headline(f), "statements": _statements(f)}
